const encoder = new TextEncoder();
const fixtures = [];

for (const sample of cases) {
    const assets = sample.assets ?? {};
    const files: DesignFiles = {
        readPage: async (path) => {
            const text = sample.pages[path];

            if (text === undefined) {
                throw new Error('not there');
            }

            return { text, size: encoder.encode(text).length };
        },
        readAsset: async (path) => {
            const asset = assets[path];

            if (asset === undefined) {
                throw new Error('not there');
            }

            return { url: `data:${asset.mime};base64,${asset.base64}`, size: Buffer.from(asset.base64, 'base64').length };
        }
    };

    fixtures.push({ ...sample, assets, html: await inlineDesignPage(files, sample.file) });
}

