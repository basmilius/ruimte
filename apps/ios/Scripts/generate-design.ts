const PAGES_TOKEN = '%PAGES%';
const FROM_TOKEN = '%FROM%';

/** A script as a raw multi-line Swift literal, which keeps its text as it is. */
function swiftScript(script: string): string {
    if (script.includes('"""#') || script.includes('\\#') || /[ \t]$/m.test(script)) {
        throw new Error('A script cannot go into a raw Swift literal as it is');
    }
    return `#"""\n${script}\n"""#`;
}

function template(script: string, tokens: string[]): string {
    for (const token of tokens) {
        if (script.split(token).length !== 2) {
            throw new Error(`The script must hold ${token} exactly once`);
        }
    }
    return script;
}

