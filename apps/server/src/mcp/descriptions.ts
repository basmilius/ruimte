/* A help text that only names the choices the schema's enum already lists, such as `grid, row, column`. */
function onlyChoices(text: string, choices: readonly string[]): boolean {
    const words = text.toLowerCase().split(/,? or |, /);

    return words.every((word) => choices.includes(word));
}

function fieldText(tool: string, key: string, field: JsonField): string | undefined {
    const prefix = tool.split('_')[0];

    for (const name of [`${tool}.${key}`, `${prefix}.${key}`, key]) {
        if (Object.hasOwn(FIELD_TEXT, name)) {
            return FIELD_TEXT[name] ?? undefined;
        }
    }

    if (field.description !== undefined && field.enum !== undefined && onlyChoices(field.description, field.enum)) {
        return undefined;
    }

    return field.description;
}

/* A tool with the words a model reads: its own description where one is written here, and each field's text. */
export function worded(tool: Tool): Tool {
    const properties = Object.fromEntries(
        Object.entries(tool.inputSchema.properties).map(([key, schema]) => {
            const { description: _generated, ...field } = schema;
            const text = fieldText(tool.name, key, schema);

            return [key, text === undefined ? field : { ...field, description: text }];
        })
    );

    return { ...tool, description: TOOL_TEXT[tool.name] ?? tool.description, inputSchema: { ...tool.inputSchema, properties } };
}
