import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { PROJECT_ICON_GROUPS, PROJECT_ICON_KEYWORDS } from '../../../apps/client/src/surface/project-icons.ts';
import { ARTIFACT_KINDS } from '../src/artifact.ts';
import {
    DeviceColorFilterSchema,
    DevicePermissionDecisionSchema,
    DevicePermissionSchema,
    DeviceTextSizeSchema,
    DeviceToggleSettingSchema,
    IOS_SIMULATOR_TOOLS
} from '../src/device.ts';
import { DRAWING_COLORS } from '../src/drawing-host.ts';
import { RuntimeModeSchema } from '../src/model.ts';
import { NodeKindSchema, PROJECT_VIEW_KINDS } from '../src/project.ts';
import { PushNotifyKindSchema } from '../src/push.ts';

/*
 * The closed lists the app offers or matches, written from the schemas and tables that own them, so no Swift file
 * keeps a copy. A list a newer machine may extend stays a list of what this version knows; the app falls back from
 * the rest. Agent names are not here: the app reads them from `provider.list`.
 */
const ios = resolve(import.meta.dir, '../../../apps/ios');
const header = '// Generated by packages/contracts/scripts/generate-swift-tables.ts; edit the TypeScript tables.\n';

function words(values: readonly string[]): string {
    return `[${values.map((value) => JSON.stringify(value)).join(', ')}]`;
}

const vocabulary = `${header}
public enum WireVocabulary {
    /// \`NodeKindSchema\`: the kinds of canvas node this version knows.
    public static let nodeKinds: [String] = ${words(NodeKindSchema.options)}

    /// \`PROJECT_VIEW_KINDS\`: the kinds of view this version knows.
    public static let viewKinds: [String] = ${words(PROJECT_VIEW_KINDS)}

    /// \`PushNotifyKindSchema\`.
    public static let pushNotifyKinds: [String] = ${words(PushNotifyKindSchema.options)}

    /// \`RuntimeModeSchema\`.
    public static let runtimeModes: [String] = ${words(RuntimeModeSchema.options)}

    /// \`ARTIFACT_KINDS\`.
    public static let artifactKinds: [String] = ${words(ARTIFACT_KINDS)}

    /// \`DRAWING_COLORS\`: the names a drawing paints with.
    public static let drawingColors: [String] = ${words(DRAWING_COLORS)}

    /// \`DeviceTextSizeSchema\`.
    public static let deviceTextSizes: [String] = ${words(DeviceTextSizeSchema.options)}

    /// \`DeviceColorFilterSchema\`.
    public static let deviceColorFilters: [String] = ${words(DeviceColorFilterSchema.options)}

    /// \`DeviceToggleSettingSchema\`.
    public static let deviceToggleSettings: [String] = ${words(DeviceToggleSettingSchema.options)}

    /// \`IOS_SIMULATOR_TOOLS\`: what a simulator that announces no tools can do.
    public static let iosSimulatorTools: [String] = ${words(IOS_SIMULATOR_TOOLS)}

    /// \`DevicePermissionSchema\`.
    public static let devicePermissions: [String] = ${words(DevicePermissionSchema.options)}

    /// \`DevicePermissionDecisionSchema\`.
    public static let devicePermissionDecisions: [String] = ${words(DevicePermissionDecisionSchema.options)}

    /// The project icons in the order a person browses them, grouped as \`PROJECT_ICON_GROUPS\` on the desktop.
    public static let projectIconGroups: [(id: String, names: [String])] = [
${PROJECT_ICON_GROUPS.map((group) => `        (${JSON.stringify(group.id)}, ${words(Object.keys(group.icons))}),`).join('\n')}
    ]

    /// The words a search finds an icon by beyond its own name, \`PROJECT_ICON_KEYWORDS\`.
    public static let projectIconKeywords: [String: [String]] = [
${Object.entries(PROJECT_ICON_KEYWORDS)
    .map(([name, keywords]) => `        ${JSON.stringify(name)}: ${words(keywords ?? [])},`)
    .join('\n')}
    ]
}
`;

const outputs = new Map<string, string>([[resolve(ios, 'Packages/RuimtePulsar/Sources/RuimtePulsar/Generated/WireVocabulary.swift'), vocabulary]]);

for (const [destination, contents] of outputs) {
    if (process.argv.includes('--check')) {
        if ((await readFile(destination, 'utf8').catch(() => '')) !== contents) {
            throw new Error(`Stale generated file: ${destination}`);
        }
    } else {
        await mkdir(resolve(destination, '..'), { recursive: true });
        await writeFile(destination, contents);
    }
}

console.log(`${process.argv.includes('--check') ? 'Checked' : 'Generated'} ${outputs.size} Swift tables.`);
